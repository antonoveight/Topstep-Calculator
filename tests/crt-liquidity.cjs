const assert=require('node:assert/strict'),fs=require('node:fs');
const source=fs.readFileSync('indicators/funded-angler-v6.pine','utf8'),k=require('./helpers/pine-crt-key-harness.cjs').createKeyHarness(source);
let cases=0;
for(const dir of [-1,1])for(const kind of [1,2,3,4,5]){
 const key=k.makeKey({kind,dir,hi:101,lo:99,knownAt:60,beforeTime:70,tf:'60'});
 const [hi,lo,c]=dir===1?[104,kind===3?98:100,103]:[kind===3?102:100,96,97];
 assert.equal(k.reaction(key,70,dir,hi,lo,c),true);cases++;
 assert.equal(k.reaction({...key,knownAt:71},70,dir,hi,lo,c),false);cases++;
 assert.equal(k.reaction({...key,dir:-dir},70,dir,hi,lo,c),false);cases++;
 assert.equal(k.reaction(key,70,dir,dir===1?110:90,dir===1?105:85,c),false);cases++;
 assert.equal(k.reaction(key,70,dir,hi,lo,c,'Swing'),kind===3);cases++;
}
const b=(t,o,h,l,c)=>({t,end:t+3600000,o,h,l,c});
const bars=[b(0,106,108,99,100),b(3600000,100,112,100,111),b(7200000,113,115,110,114)];
let zones=[];for(let n=1;n<=bars.length;n++)zones=k.zoneStep(zones,bars.slice(0,n));
const gap=zones.find(x=>x.kind===1&&x.dir===1);assert.ok(gap);assert.equal(gap.lo,108);assert.equal(gap.hi,110);assert.equal(gap.leftTime,0);assert.equal(gap.knownAt,10800000);
const ob=zones.find(x=>x.kind===2&&x.dir===1);assert.ok(ob);assert.equal(ob.lo,99);assert.equal(ob.hi,108);assert.equal(ob.knownAt,7200000);
assert.equal(zones.filter(x=>x.kind===2&&x.dir===1).length,1,'Continuing beyond an already broken OB does not recreate its discovery timestamp');
assert.ok(zones.some(x=>x.kind===4&&x.hi===106));assert.ok(zones.some(x=>x.kind===5&&x.hi===100));
assert.equal(k.reaction(gap,7200000,1,116,109,113),false);
zones=k.zoneStep(zones,[...bars,b(10800000,114,115,98,98)]);
assert.ok(!zones.some(x=>x.dir===1),'Distal close break retires bullish keys');
const old=[k.makeKey({kind:1,dir:1,lo:90,hi:95,knownAt:1})];
assert.equal(k.zoneStep(old,[b(200000000,100,105,99,103)]).length,0);
const mirrored=bars.map(x=>({...x,o:220-x.o,h:220-x.l,l:220-x.h,c:220-x.c}));let bearish=[];
for(let n=1;n<=mirrored.length;n++)bearish=k.zoneStep(bearish,mirrored.slice(0,n));
assert.deepEqual(bearish.filter(x=>x.kind===1).map(x=>[x.dir,x.lo,x.hi,x.knownAt]),[[-1,110,112,10800000]]);
assert.deepEqual(bearish.filter(x=>x.kind===2).map(x=>[x.dir,x.lo,x.hi,x.knownAt]),[[-1,112,121,7200000]]);
assert.doesNotMatch(source,/f_refreshIrl|f_level\([^\n]*"(?:ERL|IRL|iBSL|iSSL)/);
console.log(`PASS ${cases} actual key matcher checks plus closed HTF FVG/OB/open/close creation, wick anchors, knowledge times and invalidation.`);
