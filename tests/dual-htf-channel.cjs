const assert=require('node:assert/strict'),fs=require('node:fs');
const s=fs.readFileSync('indicators/funded-angler-v6.pine','utf8');
const h=require('./helpers/pine-channel-harness.cjs').createHarness(s);
const tape=[{t:100,o:104,h:108,l:102,c:106},{t:101,o:108,h:111,l:103,c:105}];
const main={id:1,kind:1,dir:-1,confirmed:100,inv:120,cp:80},higher={...main,id:2};
const a=h.state(main),b=h.state(higher);
assert.equal(h.step(main,a,tape,{requireKey:false,bias:-1}).hit,true);
assert.equal(h.step(higher,b,tape,{requireKey:false,bias:-1}).hit,true);
assert.equal(h.step(main,a,tape,{requireKey:false,bias:-1}).hit,false);
assert.equal(b.everSent,true);
const stopped=h.state({...main,id:3});
assert.equal(h.step({...main,inv:110},stopped,tape,{requireKey:false,bias:-1}).hit,false);
assert.equal(b.localStopTaken,false,'Main invalidation cannot terminate the higher channel');
const packed=s.match(/HigherSnapshot.new\(id=q0\[1\][^\r\n]+/)[0];
for(const [field,n] of [['id',0],['dir',4],['inv',7],['cp',8],['confirmed',15],['key',59]])assert.ok(packed.includes(field+'=q'+n+'[1]'));
assert.match(s,/htf \+ ":" \+ modelKey/);assert.match(s,/largerTf \+ ":" \+ higherModelKey/);
assert.match(s,/markerResults = array.from\(crtResult, higherResult\)/);
assert.equal((s.match(/f_note\(true, buyHint\)/g)||[]).length,1);
assert.equal((s.match(/f_note\(false, sellHint\)/g)||[]).length,1);
console.log('PASS actual dual-channel isolation, independent signal budgets/barriers, confirmed packed context and merged per-direction markers.');
